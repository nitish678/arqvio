def test_refusals_are_named(pinned_home: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    cell = battery_cell()
    dna = _dna("RSI_REVERSION")
    with pytest.raises(codegen.CodegenError, match="schema_version 2"):
        codegen.generate(dataclasses.replace(dna, schema_version=2), cell, magic=610_000_000)
    with pytest.raises(codegen.CodegenError, match="refused: invalid rsi_period"):
        codegen.generate(dataclasses.replace(dna, rsi_period=40), cell, magic=610_000_000)
    with pytest.raises(codegen.CodegenError, match="exec_mode 'LIMIT'"):
        codegen.generate(dataclasses.replace(dna, exec_mode="LIMIT"), cell, magic=610_000_000)
    monkeypatch.setattr(codegen, "FAMILY_GENES", {k: v for k, v in codegen.FAMILY_GENES.items() if k != "RSI_REVERSION"})
    with pytest.raises(codegen.CodegenError, match="unknown signal family 'RSI_REVERSION'"):
        codegen.generate(dna, cell, magic=610_000_000)
    monkeypatch.undo()
    with pytest.raises(codegen.CodegenError, match="no 24-hour spread matrix"):
        codegen.generate(dna, dataclasses.replace(cell, hourly_spread_points=None), magic=610_000_000)
    # W4-2: a V4 switch-genome DNA is refused until the parity EA template gains
    # switch inputs (W4-2.4). The CodeGenError must name every switch that blocked it.
    # v4 batch B: bias/filter switches are entry gates -- the live EA carries them, the parity EA refuses them as it
    # refuses the session / trend gates; management switches are still refused by name.
    gated = dataclasses.replace(dna, bias_switches=("sma",), filter_switches=("rsi",))
    with pytest.raises(codegen.CodegenError, match="entry gates .* are not in the Strategy Tester parity EA"):
        codegen.generate(gated, cell, magic=610_000_000)
    switched = dataclasses.replace(dna, mgmt_switches=("eod_close",))
    with pytest.raises(codegen.CodegenError, match=r"V4 switch genome not yet codegen-able \(switches=.*\beod_close\b.*\)"):
        codegen.generate(switched, cell, magic=610_000_000)
