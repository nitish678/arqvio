FAMILIES = ("MA_CROSS", "RSI_REVERSION", "STOCH_CROSS", "MACD_CROSS", "DONCHIAN_BREAKOUT")


def _dna(family: str, seed: int = 20261001):
    return dataclasses.replace(random_dna(np.random.default_rng(seed)), signal=family)


@pytest.mark.parametrize("family", FAMILIES)
def test_the_same_dna_and_template_give_a_byte_identical_file(pinned_home: Path, family: str) -> None:
    cell = battery_cell()
    a = codegen.generate(_dna(family), cell, magic=610_000_007)
    b = codegen.generate(_dna(family), battery_cell(), magic=610_000_007)
    assert a.source == b.source and a.source_sha256 == b.source_sha256
    assert "\r" not in a.source and a.source.endswith("\n")


def test_only_the_magic_lines_differ_between_two_magics(pinned_home: Path) -> None:
    cell = battery_cell()
    a = codegen.generate(_dna("MA_CROSS"), cell, magic=610_000_001).source.splitlines()
    b = codegen.generate(_dna("MA_CROSS"), cell, magic=610_000_002).source.splitlines()
    diff = [(x, y) for x, y in zip(a, b) if x != y]
    assert len(a) == len(b) and len(diff) == 2 and all("610000001" in x and "610000002" in y for x, y in diff)


def test_the_template_version_and_digest_are_stamped(pinned_home: Path) -> None:
    ea = codegen.generate(_dna("RSI_REVERSION"), battery_cell(), magic=610_000_000)
    v, d = codegen.TEMPLATE_VERSION, codegen.template_digest()
    assert ea.template_version == v and ea.template_digest == d
    assert f"Generated by ARQVIO {v}" in ea.source and f"template_digest {d}" in ea.source
    assert f'input string InpTemplateVersion = "{v}";' in ea.source
    assert f'const string TEMPLATE_VERSION = "{v}";' in ea.source and f'const string TEMPLATE_DIGEST = "{d}";' in ea.source


def test_the_digest_moves_when_a_template_changes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    before = codegen.template_digest()
    copy = tmp_path / "templates"
    shutil.copytree(codegen._templates_dir(), copy)
    (copy / "family_ma_cross.j2").write_text((copy / "family_ma_cross.j2").read_text() + "// x\n")
    monkeypatch.setattr(codegen, "_templates_dir", lambda: copy)
    assert codegen.template_digest() != before


def test_a_crlf_checkout_generates_the_same_file(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                                 pinned_home: Path) -> None:
    lf = codegen.generate(_dna("STOCH_CROSS"), battery_cell(), magic=610_000_000).source
    copy = tmp_path / "templates"
    shutil.copytree(codegen._templates_dir(), copy)
    for p in copy.glob("*.j2"):
        p.write_bytes(p.read_bytes().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n"))
    monkeypatch.setattr(codegen, "_templates_dir", lambda: copy)
    assert codegen.generate(_dna("STOCH_CROSS"), battery_cell(), magic=610_000_000).source == lf


def test_doubles_are_emitted_as_exact_bit_patterns(pinned_home: Path) -> None:
    cell = campaign_cell("USDCADm", "aed3bf314539ec5a")
    dna = _dna("MA_CROSS")
    cfg, _ = dna_to_strategy(dna)
    src = codegen.generate(dna, cell, magic=610_000_000).source
    for name, value in (("C_POINT", cell.spec.point), ("C_TVP", cell.spec.trade_tick_value_profit),
                        ("C_TVL", cell.spec.trade_tick_value_loss), ("C_MAX_SPREAD", cell.max_spread_points),
                        ("P_VOLUME", cfg.volume), ("P_SL_ATR", cfg.sl_atr), ("P_TP_ATR", cfg.tp_atr)):
        m = re.search(rf"{name} = FromBits\(0x([0-9A-F]{{16}})\);", src)
        assert m, name
        assert struct.unpack("<d", struct.pack("<Q", int(m.group(1), 16)))[0] == value, name
    for h, value in enumerate(cell.hourly_spread_points):
        assert f"C_HOURLY[{h}] = FromBits({codegen.bits(value)});" in src
    assert f"const int MA_FAST = {cfg.fast};" in src and f"const int MA_SLOW = {cfg.slow};" in src
    body = src.split("void InitConstants()", 1)[1]
    assert not re.search(r"=\s*-?\d+\.\d+(e-?\d+)?\s*;", body.split("double PwSum", 1)[0])  # no decimal literals


def test_bits_round_trips_every_double() -> None:
    for x in (0.0, -0.0, 1e-5, 0.7093808523920323, -8.4, 15.699999999995157, 1e300, 5e-324):
        u = int(codegen.bits(x), 16)
        assert struct.unpack("<d", struct.pack("<Q", u))[0] == x or (x == 0.0)
        assert codegen.bits(x) == "0x" + struct.pack(">d", x).hex().upper()


